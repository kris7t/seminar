import { generateUtilityClasses } from '@mui/material';
import {
  styled,
  useThemeProps,
  type SxProps,
  type Theme,
} from '@mui/material/styles';
import type { JSX, ReactNode } from 'react';

import type { ComponentTheme } from '@seminar/core';

/** Joins the given class names, skipping `undefined` and empty ones. */
function classNames(...names: (string | undefined)[]): string {
  return names.filter((name) => name !== undefined && name !== '').join(' ');
}

export interface FormulaProps {
  /** Whether the formula is shown on its own line, like `$$…$$` in TeX. */
  display?: boolean | undefined;
  /**
   * Whether the formula takes the full width of the line, e.g., for equation
   * numbers on the right.
   */
  fullWidth?: boolean | undefined;
  /** Minimum width of a full-width formula, e.g., `12.5ex`. */
  minWidth?: string | undefined;
  /**
   * The rendered formula, usually an `svg` element, which should be hidden
   * from assistive technology in favor of `mathml`.
   */
  children?: ReactNode;
  /**
   * The rendered formula as the HTML of an `svg` element, instead of the
   * children, like `DynamicFormula` renders it.
   */
  svg?: string | undefined;
  /**
   * The formula as a MathML `math` element in HTML, which is only visible to
   * assistive technology.
   *
   * The compiler writes non-ASCII characters in it as character references,
   * so that self-contained builds don't keep fonts for them.
   */
  mathml?: string | undefined;
  className?: string;
  sx?: SxProps<Theme>;
}

export type FormulaClassKey = 'root' | 'display' | 'inline' | 'svg' | 'mathml';

export const formulaClasses: Record<FormulaClassKey, string> =
  generateUtilityClasses('SeminarFormula', [
    'root',
    'display',
    'inline',
    'svg',
    'mathml',
  ]);

declare module '@mui/material/styles' {
  interface ComponentNameToClassKey {
    SeminarFormula: FormulaClassKey;
  }

  interface ComponentsPropsList {
    SeminarFormula: FormulaProps;
  }

  interface Components<Theme = unknown> {
    SeminarFormula?: ComponentTheme<'SeminarFormula', Theme> | undefined;
  }
}

// Adapted from the style sheet of the SVG output of MathJax.
const FormulaRoot = styled('span', {
  name: 'SeminarFormula',
  slot: 'Root',
})<{ ownerState: FormulaProps }>({
  position: 'relative',
  direction: 'ltr',
  whiteSpace: 'nowrap',
  [`& > svg, & > .${formulaClasses.svg} > svg`]: {
    overflow: 'visible',
    minHeight: 1,
    minWidth: 1,
  },
  variants: [
    {
      props: ({ ownerState }) => ownerState.display === true,
      style: {
        display: 'block',
        textAlign: 'center',
        justifyContent: 'center',
        margin: '0.7em 0',
        padding: '0.3em 2px',
      },
    },
    {
      props: ({ ownerState }) =>
        ownerState.display === true && ownerState.fullWidth === true,
      style: { display: 'flex' },
    },
  ],
});

// Holds the SVG given as HTML, without a box of its own.
const FormulaSvg = styled('span', {
  name: 'SeminarFormula',
  slot: 'Svg',
})({ display: 'contents' });

// Shows the MathML to assistive technology only.
const FormulaMathml = styled('span', {
  name: 'SeminarFormula',
  slot: 'Mathml',
})({
  position: 'absolute',
  inset: 0,
  display: 'block',
  padding: '1px 0 0 0',
  border: 0,
  overflow: 'hidden',
  clipPath: 'polygon(0 0, 0 1px, 1px 1px, 1px 0)',
  userSelect: 'none',
});

/**
 * A formula rendered by MathJax, as created from `$…$` and `$$…$$` in decks
 * written in MDX.
 *
 * Can be themed as `SeminarFormula` in the `components` of the MUI theme. The
 * math font is chosen when the deck is compiled (see `SeminarConfig`).
 */
export function Formula(inProps: FormulaProps): JSX.Element {
  const props = useThemeProps({ props: inProps, name: 'SeminarFormula' });
  const {
    display = false,
    fullWidth = false,
    minWidth,
    className,
    children,
    svg,
    mathml,
    ...other
  } = props;
  return (
    <FormulaRoot
      as={display ? 'div' : 'span'}
      className={classNames(
        formulaClasses.root,
        display ? formulaClasses.display : formulaClasses.inline,
        className,
      )}
      ownerState={{ ...props, display, fullWidth }}
      style={fullWidth && minWidth !== undefined ? { minWidth } : undefined}
      {...other}
    >
      {svg === undefined ? (
        children
      ) : (
        <FormulaSvg
          className={formulaClasses.svg}
          // Rendered by MathJax from TeX.
          // eslint-disable-next-line @eslint-react/dom-no-dangerously-set-innerhtml
          dangerouslySetInnerHTML={{ __html: svg }}
        />
      )}
      {mathml !== undefined && (
        <FormulaMathml
          className={formulaClasses.mathml}
          // Generated by the compiler from the TeX source of the deck.
          // eslint-disable-next-line @eslint-react/dom-no-dangerously-set-innerhtml
          dangerouslySetInnerHTML={{ __html: mathml }}
        />
      )}
    </FormulaRoot>
  );
}
